#!/usr/bin/env python3
"""Generate the journal's indexes from entry front matter, and check the entries.

The journal is a directory of dated, immutable entries. Everything a reader navigates
by is generated from their front matter by this script: the front page, the entry
list, the entry section on every topic page, the digest list and the MyST table of
contents. Nothing here is hand-maintained, so nothing here can go stale.

    python3 scripts/build_index.py          # regenerate
    python3 scripts/build_index.py --check  # validate only; exit 1 on a problem

An entry's front matter. `title`, `date` and `authors` are MyST's own; the journal's
fields sit under `options:`, the one key MyST passes through without a warning:

    title:   one line
    date:    YYYY-MM-DD, and the filename starts with the same date
    authors: [name or session, ...]
    options:
      kind:    finding | dead-end | measurement | decision | digest
      status:  live | superseded | absorbed | discarded   (default live)
      topics:  [slug, ...]  each the stem of a page under topics/, benchmarks/ or campaigns/
      links:   [url or path, ...]        the evidence
      superseded_by / absorbed_into:     a path or URL, when status says so
"""

import argparse
import collections
import datetime
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
KINDS = ("finding", "dead-end", "measurement", "decision", "digest")
STATUSES = ("live", "superseded", "absorbed", "discarded")
PAGE_GROUPS = ("topics", "benchmarks", "campaigns")
BEGIN = "<!-- BEGIN ENTRIES (generated by scripts/build_index.py; do not edit) -->"
END = "<!-- END ENTRIES -->"
TOC_BEGIN = "  # BEGIN GENERATED TOC"
TOC_END = "  # END GENERATED TOC"


def split_front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n?", text, re.S)
    if not m:
        return None, text
    return yaml.safe_load(m.group(1)) or {}, text[m.end():]


def load_entries():
    entries, problems = [], []
    for path in sorted((ROOT / "entries").glob("*.md")):
        fm, body = split_front_matter(path.read_text())
        rel = path.relative_to(ROOT)
        if fm is None:
            problems.append(f"{rel}: no front matter")
            continue
        stray = [k for k in ("kind", "status", "topics", "links") if k in fm]
        if stray:
            problems.append(f"{rel}: {', '.join(stray)} belong under options:, not at the top level")
        opts = fm.get("options") or {}
        date = fm.get("date")
        if isinstance(date, datetime.date):
            date_s = date.isoformat()
        else:
            date_s = str(date or "")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date_s):
            problems.append(f"{rel}: date missing or not YYYY-MM-DD")
        elif not path.name.startswith(date_s):
            problems.append(f"{rel}: filename does not start with its date {date_s}")
        if opts.get("kind") not in KINDS:
            problems.append(f"{rel}: options.kind must be one of {KINDS}")
        status = opts.get("status", "live")
        if status not in STATUSES:
            problems.append(f"{rel}: options.status must be one of {STATUSES}")
        if status == "superseded" and not opts.get("superseded_by"):
            problems.append(f"{rel}: superseded without superseded_by")
        if status == "absorbed" and not opts.get("absorbed_into"):
            problems.append(f"{rel}: absorbed without absorbed_into")
        topics = opts.get("topics") or []
        if not topics and opts.get("kind") != "digest":
            problems.append(f"{rel}: no topics")
        for t in topics:
            if not page_for(t):
                problems.append(f"{rel}: topic '{t}' has no page under {PAGE_GROUPS}")
        if not fm.get("title"):
            problems.append(f"{rel}: no title")
        entries.append(dict(path=path, rel=rel, fm=opts, date=date_s, status=status,
                            kind=opts.get("kind"), topics=topics, title=fm.get("title", path.stem)))
    entries.sort(key=lambda e: (e["date"], e["path"].name), reverse=True)
    return entries, problems


def page_for(slug):
    for group in PAGE_GROUPS:
        p = ROOT / group / f"{slug}.md"
        if p.exists():
            return p
    return None


def page_title(path):
    fm, body = split_front_matter(path.read_text())
    if fm and fm.get("title"):
        return fm["title"]
    m = re.search(r"^# (.+)$", body, re.M)
    return m.group(1) if m else path.stem


def entry_line(e, prefix):
    return f"- {e['date']} · [{e['title']}]({prefix}entries/{e['path'].name}) · {e['kind']}"


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        return True
    return False


def render_topic_sections(entries):
    changed = []
    by_topic = collections.defaultdict(list)
    for e in entries:
        for t in e["topics"]:
            by_topic[t].append(e)
    for group in PAGE_GROUPS:
        for page in sorted((ROOT / group).glob("*.md")):
            if page.name == "index.md":
                continue
            text = page.read_text()
            if BEGIN not in text:
                text = text.rstrip("\n") + "\n\n" + BEGIN + "\n" + END + "\n"
            es = by_topic.get(page.stem, [])
            live = [e for e in es if e["status"] == "live"]
            retired = [e for e in es if e["status"] != "live"]
            lines = [BEGIN, "", "## Entries", ""]
            if not es:
                lines.append("No entries yet.")
            if live:
                lines += [entry_line(e, "../") for e in live]
            if retired:
                lines += ["", "Retired (superseded, absorbed or discarded):", ""]
                for e in retired:
                    where = e["fm"].get("superseded_by") or e["fm"].get("absorbed_into") or ""
                    lines.append(entry_line(e, "../") + f" · {e['status']}" + (f" → {where}" if where else ""))
            lines += ["", END]
            block = "\n".join(lines)
            new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
            if write_if_changed(page, new):
                changed.append(page)
    return changed


def render_entries_index(entries):
    lines = ["---", "title: All entries", "---", "",
             "Every entry, newest first. An entry is written once and never edited; its",
             "status says whether it still stands. The topic pages hold the current reading.", ""]
    by_month = collections.OrderedDict()
    for e in entries:
        by_month.setdefault(e["date"][:7], []).append(e)
    for month, es in by_month.items():
        lines += [f"## {month}", ""]
        for e in es:
            tag = "" if e["status"] == "live" else f" · {e['status']}"
            topics = ", ".join(e["topics"])
            lines.append(entry_line(e, "") + (f" · {topics}" if topics else "") + tag)
        lines.append("")
    write_if_changed(ROOT / "entries.md", "\n".join(lines))


def render_digests_index():
    digests = sorted((ROOT / "digests").glob("*.md"), reverse=True)
    lines = ["---", "title: Weekly digests", "---", "",
             "One page a week: what was learned, what shipped, what is stuck.", ""]
    for d in digests:
        lines.append(f"- [{page_title(d)}](digests/{d.name})")
    write_if_changed(ROOT / "digests.md", "\n".join(lines) + "\n")
    return digests


def render_front_page(entries, digests):
    lines = ["---", "title: Underworld journal", "---", "",
             "The lab journal of the Underworld project: what was tried, what happened, and",
             "what we now think, one dated entry at a time. Entries are never edited; a topic",
             "page says what currently stands, and the weekly digest says what moved.", ""]
    if digests:
        lines += ["## This week", "", f"[{page_title(digests[0])}](digests/{digests[0].name})", ""]
    lines += ["## Topics", ""]
    for group in PAGE_GROUPS:
        pages = [p for p in sorted((ROOT / group).glob("*.md")) if p.name != "index.md"]
        if not pages:
            continue
        lines.append(f"**{group.capitalize()}**")
        lines.append("")
        for p in pages:
            n_live = sum(1 for e in entries if p.stem in e["topics"] and e["status"] == "live")
            lines.append(f"- [{page_title(p)}]({group}/{p.name}) · {n_live} live")
        lines.append("")
    lines += ["## Recent entries", ""]
    lines += [entry_line(e, "") for e in entries[:20]]
    lines += ["", "[All entries](entries.md)", ""]
    write_if_changed(ROOT / "index.md", "\n".join(lines))


def render_toc(entries, digests):
    y = ROOT / "myst.yml"
    text = y.read_text()
    lines = [TOC_BEGIN, "  toc:", "    - file: index.md"]
    lines += ["    - title: Digests", "      children:", "        - file: digests.md"]
    lines += [f"        - file: digests/{d.name}" for d in digests]
    for group in PAGE_GROUPS:
        pages = [p for p in sorted((ROOT / group).glob("*.md")) if p.name != "index.md"]
        if not pages:
            continue
        lines += [f"    - title: {group.capitalize()}", "      children:"]
        lines += [f"        - file: {group}/{p.name}" for p in pages]
    lines += ["    - title: Entries", "      children:", "        - file: entries.md"]
    by_month = collections.OrderedDict()
    for e in entries:
        by_month.setdefault(e["date"][:7], []).append(e)
    for month, es in by_month.items():
        lines += [f"        - title: \"{month}\"", "          children:"]
        lines += [f"            - file: entries/{e['path'].name}" for e in es]
    lines.append(TOC_END)
    block = "\n".join(lines)
    new = re.sub(re.escape(TOC_BEGIN) + r".*?" + re.escape(TOC_END), lambda m: block, text, flags=re.S)
    write_if_changed(y, new)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only")
    args = ap.parse_args()
    entries, problems = load_entries()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    if args.check:
        print(f"{len(entries)} entries, all valid")
        return
    changed = render_topic_sections(entries)
    render_entries_index(entries)
    digests = render_digests_index()
    render_front_page(entries, digests)
    render_toc(entries, digests)
    print(f"{len(entries)} entries; {len(changed)} topic pages updated")


if __name__ == "__main__":
    main()
